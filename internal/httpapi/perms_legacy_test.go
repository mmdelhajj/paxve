func TestPresetsMatchLegacyRoles(t *testing.T) {
	builtin := []string{RoleAdmin, RoleAccountant, RoleDataEntry, RoleReadOnly, RoleCollector, RoleCashier}
	for _, lr := range legacyRoutes {
		perm, ok := routePerms[lr.pattern]
		if !ok {
			t.Errorf("%s: no permission declared", lr.pattern)
			continue
		}
		var want, got []string
		for _, b := range builtin {
			kindOK := lr.kind == "field" || (b != RoleCollector && b != RoleCashier)
			if kindOK && (lr.roles == "*" || slices.Contains(strings.Fields(lr.roles), b)) {
				want = append(want, b)
			}
			if kindOK && (perm == permAny || slices.Contains(presets[b], perm)) {
				got = append(got, b)
			}
		}
		sort.Strings(want)
		sort.Strings(got)
		if !slices.Equal(want, got) {
			t.Errorf("%s (%s): legacy roles %v, preset roles %v", lr.pattern, perm, want, got)
		}
	}
}
