INSERT INTO currencies (code, name, symbol, decimals, name_ar, name_fr)
SELECT code, name, symbol, decimals, name_ar, name_fr FROM iso_currencies
ON CONFLICT (code) DO UPDATE SET decimals = EXCLUDED.decimals, name_ar = EXCLUDED.name_ar, name_fr = EXCLUDED.name_fr;

-- where each rate came from: typed by a user, or fetched automatically (never overwrites a typed rate)
ALTER TABLE exchange_rates ADD COLUMN source text NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'auto'));

-- automatic daily rates: off by default; currencies listed in manual_rate_currencies are never fetched
-- (the Lebanese market rate is not the published one)
ALTER TABLE companies ADD COLUMN auto_rates boolean NOT NULL DEFAULT false;
ALTER TABLE companies ADD COLUMN manual_rate_currencies text[] NOT NULL DEFAULT ARRAY['LBP'];
ALTER TABLE companies ADD COLUMN auto_rates_at timestamptz;

-- +goose Down
ALTER TABLE companies DROP COLUMN IF EXISTS auto_rates_at;
ALTER TABLE companies DROP COLUMN IF EXISTS manual_rate_currencies;
ALTER TABLE companies DROP COLUMN IF EXISTS auto_rates;
ALTER TABLE exchange_rates DROP COLUMN IF EXISTS source;
ALTER TABLE currencies DROP COLUMN IF EXISTS name_fr;
ALTER TABLE currencies DROP COLUMN IF EXISTS name_ar;
